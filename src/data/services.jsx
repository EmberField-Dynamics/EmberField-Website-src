export const productsByCategory = (catId) => PRODUCTS.filter((p) => p.cat === catId)
export const getProduct = (slug) => PRODUCTS.find((p) => p.slug === slug)
export const relatedProducts = (slug, limit = 3) => {
  const prod = getProduct(slug)
  if (!prod) return []
  return PRODUCTS.filter((p) => p.slug !== slug && p.cat === prod.cat).slice(0, limit)
}